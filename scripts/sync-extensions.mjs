#!/usr/bin/env node
/**
 * Regenerates src/extensions.ts from the source files under extension/.
 * The Worker bundles these embedded copies to serve /extension/download/*.
 *
 * Usage: node scripts/sync-extensions.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const readText = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
const readB64 = f => fs.readFileSync(path.join(ROOT, f)).toString('base64');
const lit = s => JSON.stringify(s);

const out = `// AUTO-GENERATED by scripts/sync-extensions.mjs — do not edit by hand.
// Edit the source files under extension/ then run: node scripts/sync-extensions.mjs
import { zipSync, strToU8 } from 'fflate';

const MANIFEST_CHROME = ${lit(readText('extension/manifest.json'))};
const MANIFEST_FIREFOX = ${lit(readText('extension/manifest_firefox.json'))};
const BACKGROUND_JS = ${lit(readText('extension/background.js'))};
const POPUP_HTML = ${lit(readText('extension/popup.html'))};
const POPUP_JS = ${lit(readText('extension/popup.js'))};
const ICON_SVG = ${lit(readText('extension/icons/icon.svg'))};
const ICON_16_B64 = ${lit(readB64('extension/icons/icon-16.png'))};
const ICON_48_B64 = ${lit(readB64('extension/icons/icon-48.png'))};
const ICON_128_B64 = ${lit(readB64('extension/icons/icon-128.png'))};

function b64ToU8(b64: string): Uint8Array {
  const bin = atob(b64);
  const u8 = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) {
    u8[i] = bin.charCodeAt(i);
  }
  return u8;
}

export function createExtensionZip(browserType: 'chrome' | 'firefox'): Uint8Array {
  const manifest = browserType === 'chrome' ? MANIFEST_CHROME : MANIFEST_FIREFOX;

  const files = {
    'manifest.json': strToU8(manifest),
    'background.js': strToU8(BACKGROUND_JS),
    'popup.html': strToU8(POPUP_HTML),
    'popup.js': strToU8(POPUP_JS),
    'icons/icon-16.png': b64ToU8(ICON_16_B64),
    'icons/icon-48.png': b64ToU8(ICON_48_B64),
    'icons/icon-128.png': b64ToU8(ICON_128_B64),
    'icons/icon.svg': strToU8(ICON_SVG),
  };

  return zipSync(files);
}
`;

fs.writeFileSync(path.join(ROOT, 'src/extensions.ts'), out);
console.log('src/extensions.ts regenerated from extension/ sources');
